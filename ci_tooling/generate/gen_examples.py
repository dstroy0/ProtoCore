"""Generate the example index in docs/EXAMPLES.md from the examples/ directory.

The prose (intro, build-and-run, troubleshooting) is hand-maintained; the per-group
lists of examples and the total count are generated by scanning `examples/`, so they
can never drift from the tree (they had - the Foundation group silently lost 16
entries before this existed). Each OSI-layer group dir is listed in order, its
example dirs sorted alphabetically, as `·`-separated links.

Run from the repo root:
    python ci_tooling/generate/gen_examples.py            # rewrite the index
    python ci_tooling/generate/gen_examples.py --check    # CI: fail if stale
"""

import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib"))
import doc_region as dr  # noqa: E402  (path set above)

ROOT = dr.repo_root(__file__)
EXAMPLES_DIR = os.path.join(ROOT, "examples")
EXAMPLES_MD = os.path.join(ROOT, "docs", "EXAMPLES.md")

# Link each example to its README, relative: on github.com the README renders in place, and
# Doxygen (which now takes examples/**/README.md as input, see docs/Doxyfile) resolves the same
# relative link to the rendered Pages page. So the walkthroughs live ON the site, not as bare
# repo links. Each README documents its example directory, so the pages nest under the Files
# tree by path (no nav-root flood); this index just links them by OSI-layer group.

REGION = dr.Region(EXAMPLES_MD, "EXAMPLE INDEX", dr.tool_id(__file__))

# Ordered OSI-layer groups: (directory name, heading, one-line description).
GROUPS = [
    (
        "Foundation",
        "Foundation",
        "Start here: the core tutorial path (Basic -> Advanced -> Expert -> Sysadmin -> "
        "Configuration), then the server-architecture examples - the preempting task queue, "
        "lanes, and interface forwarding:",
    ),
    (
        "Peripherals",
        "Peripherals",
        "On-chip and add-on interface hardware - Ethernet (internal + W5500), CAN, Wi-Fi "
        "capture, and DMA ingest:",
    ),
    (
        "Drivers",
        "Drivers",
        "External chip drivers over I2C / SPI / UART - sensors, ADC / PWM / current monitors, "
        "an RTC, and radio-module gateways:",
    ),
    ("L4-Transport", "L4 Transport", "Connections, encryption, and flood defense:"),
    ("L5-Session", "L5 Session", "Interactive consoles:"),
    ("L6-Presentation", "L6 Presentation", "Parsing, codecs, auth, WebSocket/SSE:"),
    ("L7-Application", "L7 Application", "Routing, protocols, services, and clients:"),
]


def examples_in(group_dir):
    """Return the example dirs under a group (each holds a README.md), sorted alphabetically.

    Alphabetical (case-insensitive) gives a deterministic, filesystem-independent order so the
    CI --check never diverges from a local regen by readdir order.
    """
    path = os.path.join(EXAMPLES_DIR, group_dir)
    names = [
        n
        for n in os.listdir(path)
        if os.path.isdir(os.path.join(path, n)) and os.path.isfile(os.path.join(path, n, "README.md"))
    ]
    return sorted(names, key=str.lower)


def build_index():
    """Return (region body, total example count). Markers are added by dr.apply."""
    parts = []
    total = 0
    for group_dir, heading, desc in GROUPS:
        names = examples_in(group_dir)
        total += len(names)
        links = [f"[{n}](../examples/{group_dir}/{n}/README.md)" for n in names]
        parts += [f"## {heading}", "", desc, "", " ·\n".join(links), ""]
    return "\n".join(parts), total


def main():
    check = "--check" in sys.argv[1:]
    body, total = build_index()

    # The example count also appears in prose OUTSIDE the region. It used to be
    # patched with re.sub(count=1), which silently left the number stale if that
    # sentence was ever reworded; re_sub_once fails instead.
    def patch_count(text):
        return dr.re_sub_once(text, r"ships \d+ runnable examples",
                              f"ships {total} runnable examples", "example count in prose")

    return dr.apply(EXAMPLES_MD, {REGION: body}, check=check, transform=patch_count)


if __name__ == "__main__":
    main()
