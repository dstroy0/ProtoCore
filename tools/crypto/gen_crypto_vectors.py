# The group-14 modexp is its own table for the same reason: three 256-octet operands a row.
BN_SPECS = [
    (
        "rfc3526_group14_modexp.json",
        "KAT_GROUP14",
        "KatGroup14",
        [("base", "hex"), ("exp", "hex"), ("out", "hex"), ("comment", "str")],
    ),
]


def emit_field(v, key, kind):
    if kind == "valid":
        return "1" if v["result"] == "valid" else "0"
    if kind == "int":
        return str(int(v.get(key, 0) or 0))
    return '"%s"' % (v.get(key, "") or "")


def emit(out, banner, specs):
    lines = [
        "// Generated by tools/crypto/gen_crypto_vectors.py from test/vectors/*.json - do not edit.",
        "// %s" % banner,
        "// clang-format off",
        "",
    ]
    total = 0
    for fname, arr, struct, fields in specs:
        with open(os.path.join(VEC_DIR, fname)) as f:
            doc = json.load(f)
        src = doc.get("source", "")
        commit = doc.get("commit", "")
        prov = "%s%s" % (src, (" @ " + commit) if commit else "")
        lines.append("// %s -- %s (%d vectors)" % (arr, prov, len(doc["vectors"])))
        lines.append("static const %s %s[] = {" % (struct, arr))
        for v in doc["vectors"]:
            cells = [str(v["tcId"])]
            cells += [emit_field(v, k, kind) for (k, kind) in fields]
            lines.append("    {%s}," % ", ".join(cells))
        lines.append("};")
        lines.append("")
        total += len(doc["vectors"])
    lines.append("// clang-format on")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d vectors across %d primitives)" % (os.path.relpath(out, ROOT), total, len(specs)))


def main():
    emit(OUT, "External crypto known-answer vectors (Project Wycheproof + RFC appendices).", SPECS)
    emit(RSA_OUT, "RSASSA-PKCS1-v1.5 over RSA-2048 (Project Wycheproof verify + openssl sign).", RSA_SPECS)
    emit(BN_OUT, "RFC 3526 group-14 modular exponentiation (residues from CPython pow()).", BN_SPECS)


if __name__ == "__main__":
    main()
