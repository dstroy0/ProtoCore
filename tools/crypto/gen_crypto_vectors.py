# Compile the vendored external crypto KAT vectors (test/vectors/*.json, produced
# by tools/crypto/curate_crypto_vectors.py) into a C table the native test loops over:
# test/unit/src/crypto/mac/test_crypto_kat/kat_data.inc. Deterministic and offline - it only reads
# the committed JSON, so CI can re-run it and diff to catch a stale .inc.
#
# Each vector is emitted as a struct of hex C-strings (decoded at runtime by the
# host test); the struct layouts live in test/unit/src/crypto/mac/test_crypto_kat/test_crypto_kat.c.

import json
import os

from tools.ci_tooling.lib import doc_region as dr

ROOT = dr.repo_root(__file__)
VEC_DIR = os.path.join(ROOT, "test", "vectors")
OUT = os.path.join(ROOT, "test", "unit", "src", "crypto", "mac", "test_crypto_kat", "kat_data.inc")
RSA_OUT = os.path.join(ROOT, "test", "unit", "src", "crypto", "asymmetric", "test_rsa_kat", "rsa_kat_data.inc")
BN_OUT = os.path.join(ROOT, "test", "unit", "src", "crypto", "asymmetric", "test_bignum_group14", "bignum_kat_data.inc")

# json file -> (C array name, C struct type, ordered emit fields). Each field is
# (json_key, kind); kind "hex"/"int" pull that key, "valid" derives 1/0 from the
